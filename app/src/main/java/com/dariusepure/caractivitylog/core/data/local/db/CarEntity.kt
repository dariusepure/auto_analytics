package com.dariusepure.caractivitylog.core.data.local.db

import androidx.room.Entity
import androidx.room.PrimaryKey
import com.dariusepure.caractivitylog.core.domain.Car
import java.util.Date

@Entity(tableName = "cars")
data class CarEntity(
    @PrimaryKey val id: String,
    val userId: String = "guest",
    val name: String = "",
    val licensePlate: String = "",
    val plateCountry: String = "",
    val make: String = "",
    val model: String = "",
    val vin: String = "",
    val year: Int = 0,
    val engineSize: String = "",
    val fuelType: String = "",
    val fuelSystem: String = "",
    val color: String = "",
    val power: Int = 0,
    val powerUnit: String = "hp",
    val torque: Int = 0,
    val engineCode: String = "",
    val engineLayout: String = "",
    val cylinderLayout: String = "",
    val length: Int = 0,
    val width: Int = 0,
    val height: Int = 0,
    val wheelbase: Int = 0,
    val emissionStandard: String = "",
    val aspiration: String = "",
    val fuelTankCapacity: Double = 0.0,
    val batteryCapacity: Double = 0.0,
    val drivetrain: String = "",
    val gearboxType: String = "",
    val gears: String = "",
    val frontSuspension: String = "",
    val rearSuspension: String = "",
    val frontBrakes: String = "",
    val rearBrakes: String = "",
    val vehicleType: String = "",
    val manufacturingCountry: String = "",
    val topSpeed: Double = 0.0,
    val acceleration0to100: Double = 0.0,
    val fuelConsumptionCombined: Double = 0.0,
    val fuelConsumptionUrban: Double = 0.0,
    val fuelConsumptionExtraUrban: Double = 0.0,
    val co2Emissions: Int = 0,
    val weight: Int = 0,
    val numberOfSeats: Int = 0,
    val numberOfCylinders: Int = 0,
    val valvesPerCylinder: Int = 0,
    val numberOfDoors: Int = 0,
    val bootSpace: Int = 0,
    val tireWidth: Int = 0,
    val tireAspectRatio: Int = 0,
    val tireDiameter: Int = 0,
    val equipmentsRaw: String = "",
    val accentColor: Long? = null,
    val createdAtTimestamp: Long = System.currentTimeMillis(),
    val updatedAtTimestamp: Long = System.currentTimeMillis(),
    val activityCount: Int = 0,
    val airbags: Int = 0,
    val generation: String = "",
    val engineVariant: String = "",
    val isPendingSync: Boolean = false
)

fun CarEntity.toDomain(): Car {
    val equipList = if (equipmentsRaw.isBlank()) emptyList() else equipmentsRaw.split(",")
    return Car(
        id = id,
        name = name,
        licensePlate = licensePlate,
        plateCountry = plateCountry,
        make = make,
        model = model,
        vin = vin,
        year = year,
        engineSize = engineSize,
        fuelType = fuelType,
        fuelSystem = fuelSystem,
        color = color,
        power = power,
        powerUnit = powerUnit,
        torque = torque,
        engineCode = engineCode,
        engineLayout = engineLayout,
        cylinderLayout = cylinderLayout,
        length = length,
        width = width,
        height = height,
        wheelbase = wheelbase,
        emissionStandard = emissionStandard,
        aspiration = aspiration,
        fuelTankCapacity = fuelTankCapacity,
        batteryCapacity = batteryCapacity,
        drivetrain = drivetrain,
        gearboxType = gearboxType,
        gears = gears,
        frontSuspension = frontSuspension,
        rearSuspension = rearSuspension,
        frontBrakes = frontBrakes,
        rearBrakes = rearBrakes,
        vehicleType = vehicleType,
        manufacturingCountry = manufacturingCountry,
        topSpeed = topSpeed,
        acceleration0to100 = acceleration0to100,
        fuelConsumptionCombined = fuelConsumptionCombined,
        fuelConsumptionUrban = fuelConsumptionUrban,
        fuelConsumptionExtraUrban = fuelConsumptionExtraUrban,
        co2Emissions = co2Emissions,
        weight = weight,
        numberOfSeats = numberOfSeats,
        numberOfCylinders = numberOfCylinders,
        valvesPerCylinder = valvesPerCylinder,
        numberOfDoors = numberOfDoors,
        bootSpace = bootSpace,
        tireWidth = tireWidth,
        tireAspectRatio = tireAspectRatio,
        tireDiameter = tireDiameter,
        equipments = equipList,
        accentColor = accentColor,
        createdAt = Date(createdAtTimestamp),
        updatedAt = Date(updatedAtTimestamp),
        activityCount = activityCount,
        airbags = airbags,
        generation = generation,
        engineVariant = engineVariant,
        isPendingSync = isPendingSync
    )
}

fun Car.toEntity(userId: String = "guest"): CarEntity {
    return CarEntity(
        id = id,
        userId = userId,
        name = name,
        licensePlate = licensePlate,
        plateCountry = plateCountry,
        make = make,
        model = model,
        vin = vin,
        year = year,
        engineSize = engineSize,
        fuelType = fuelType,
        fuelSystem = fuelSystem,
        color = color,
        power = power,
        powerUnit = powerUnit,
