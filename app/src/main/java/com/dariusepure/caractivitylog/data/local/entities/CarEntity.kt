package com.dariusepure.caractivitylog.data.local.entities

import androidx.room.Entity
import androidx.room.Index
import androidx.room.PrimaryKey
import com.dariusepure.caractivitylog.domain.Car
import java.util.Date

@Entity(
    tableName = "cars",
    indices = [Index("userId")]
)
data class CarEntity(
    @PrimaryKey val id: String,
    val userId: String,
    val name: String,
    val licensePlate: String,
    val plateCountry: String,
    val make: String,
    val model: String,
    val vin: String,
    val year: Int,
    val engineSize: String,
    val fuelType: String,
    val fuelSystem: String,
    val color: String,
    val power: Int,
    val powerUnit: String,
    val torque: Int,
    val engineCode: String,
    val engineLayout: String,
    val cylinderLayout: String,
    val length: Int,
    val width: Int,
    val height: Int,
    val wheelbase: Int,
    val emissionStandard: String,
    val aspiration: String,
    val fuelTankCapacity: Double,
    val batteryCapacity: Double,
    val drivetrain: String,
    val gearboxType: String,
    val gears: String,
    val frontSuspension: String,
    val rearSuspension: String,
    val frontBrakes: String,
    val rearBrakes: String,
    val vehicleType: String,
    val manufacturingCountry: String,
    val topSpeed: Double,
    val acceleration0to100: Double,
    val fuelConsumptionCombined: Double,
    val fuelConsumptionUrban: Double,
    val fuelConsumptionExtraUrban: Double,
    val co2Emissions: Int,
    val weight: Int,
    val numberOfSeats: Int,
    val numberOfCylinders: Int,
    val valvesPerCylinder: Int,
    val numberOfDoors: Int,
    val bootSpace: Int,
    val tireWidth: Int,
    val tireAspectRatio: Int,
    val tireDiameter: Int,
    val equipments: List<String>,
    val accentColor: Long?,
    val createdAt: Date,
    val updatedAt: Date,
    val activityCount: Int,
    val airbags: Int,
    val generation: String,
    val engineVariant: String,
    val isPendingSync: Boolean
)

